/**
 * Finds a product by its slug, numericId, id, or alias
 */
export function getProductBySlug(rawSlug) {
  if (!rawSlug) return null;
  const normalized = String(rawSlug).trim().toLowerCase();
  const canonicalSlug = slugAliases[normalized] || normalized;

  return (
    allProducts.find(
      (p) =>
        p.slug.toLowerCase() === canonicalSlug ||
        p.slug.toLowerCase() === normalized ||
        p.id.toLowerCase() === normalized ||
        String(p.numericId) === normalized
    ) || null
  );
}

/**
 * Returns similar / recommended products for a given product
 */
export function getSimilarProducts(product, limit = 4) {
  if (!product) return [];

  const others = allProducts.filter(
    (p) => p.slug !== product.slug && p.id !== product.id
  );

  // 1. Same type & same category
  const sameCategory = others.filter(
    (p) => p.type === product.type && p.category === product.category
  );

  // 2. Same type (different category)
  const sameType = others.filter(
    (p) => p.type === product.type && p.category !== product.category
  );

  // 3. Different type
  const differentType = others.filter((p) => p.type !== product.type);

  const combined = [...sameCategory, ...sameType, ...differentType];
  return combined.slice(0, limit);
}

